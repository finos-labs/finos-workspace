import type { Widget } from "~/components/types";
import { uuidv4 } from "~/lib/utils";

function getHostname(url: string): string {
  try {
    return new URL(url).hostname || "Website";
  } catch {
    return "Website";
  }
}

export function buildIframeWidget(
  url: string,
  source: string,
  innerTab?: string,
): Widget {
  return {
    id: uuidv4(),
    name: getHostname(url),
    widgetId: "iframe",
    description: `Iframe for ${url}. Generated by ${source}`,
    type: "custom",
    storage: { html: url },
    ...(innerTab ? { innerTab } : {}),
  };
}
